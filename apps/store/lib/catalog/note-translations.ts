// notes read the same in every locale. That shows up in four places at once —
// the scent pyramid, the generated description, the /notes index and the
// catalogue's note rail — which is why translating the notes is worth more than
// translating the 352 scraped product descriptions ever was: one short term,
// fixed once, corrects every sentence it appears in.
//
