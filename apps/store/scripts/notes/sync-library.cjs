const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../../../..');
const directory = path.join(root, 'docs/design/note-library-v1');
const entries = [];
for (const queue of [1,2,3]) {
  const file = path.join(directory, `manifest-${queue}.json`);
  if (!fs.existsSync(file)) continue;
  for (const row of JSON.parse(fs.readFileSync(file,'utf8'))) {
    if (!row.slug || !['concept','specimen'].includes(row.kind) || !row.url?.startsWith('/notes/labor-library-v1/')) throw new Error('Invalid manifest row');
    if (!fs.existsSync(path.join(root,'apps/store/public',row.url))) throw new Error(`Missing asset ${row.slug}`);
    entries.push(row);
  }
}
const assets = Object.fromEntries(entries.sort((a,b)=>a.slug.localeCompare(b.slug)).map(row=>[row.slug,{src:row.url,representative:row.kind==='concept'}]));
fs.writeFileSync(path.join(root,'apps/store/lib/catalog/note-library.generated.ts'),'// Generated by scripts/notes/sync-library.cjs. Only completed, validated assets appear here.\nexport const NOTE_LIBRARY_ASSETS: Readonly<Record<string, { src: string; representative: boolean }>> = '+JSON.stringify(assets,null,2)+';\n');
const jobs = JSON.parse(fs.readFileSync(path.join(directory,'jobs.json'),'utf8'));
fs.writeFileSync(path.join(directory,'progress.json'),JSON.stringify({total:jobs.length,completed:entries.length,remaining:jobs.filter(row=>!assets[row.slug]).map(row=>row.slug)},null,2));
console.log(JSON.stringify({completed:entries.length,total:jobs.length}));
